"""NWSDB Rates 2026 (RB 2025 Rev. 01-2026, circular CQS/22/2026/98 of 14.10.2026) -> src/core/ratebook2026.data.js
usage: python3 rb2026.py <pdftotext -layout output> <out.js>
Only the tables the circular replaces are read (Annexes 01, 02, 03, 06, 08, 09, 12, 14); the other sections of the
2025 book are scaled by the circular's adjustment factors in ratebook.js."""
import json, re, sys
src, out = sys.argv[1], sys.argv[2]
P = open(src).read().split('\f')
num = lambda s: float(s.replace(',', ''))
def rows(pg, n, dnmin=0):
    res = []
    for ln in P[pg - 1].split('\n'):
        m = re.match(r'^\s*(\d{2,4})\s*(?:SCJ|RRJ)?\s+((?:[\d,]+\.\d\d\s+){%d,}[\d,]+\.\d\d)\s*$' % (n - 1), ln)
        if m and int(m.group(1)) >= dnmin:
            v = [num(x) for x in m.group(2).split()]
            if len(v) == n: res.append([int(m.group(1))] + v)
    return res
def expect(name, r, k):
    assert len(r) == k, f'{name}: {len(r)} rows, expected {k}'
    return r
D = {}
# Annex 01 – PVC
p7 = expect('A-PVC/01', rows(5, 2), 6) if False else None
pvc_lines = [l for l in P[4].split('Table A-PVC/02')[0].split('\n')]
def pvc_supply(text):
    r = []
    for ln in text.split('\n'):
        m = re.match(r'^\s*(\d{2,3})\s*(?:SCJ|RRJ)\s+([\d,]+\.\d\d)\s+([\d,]+\.\d\d)\s*$', ln)
        if m: r.append([int(m.group(1)), num(m.group(2)), num(m.group(3))])
    return r
a, b = P[4].split('Table A-PVC/02')
D['pvc'] = {'pnt7': expect('A-PVC/01', pvc_supply(a), 6), 'pnt11': expect('A-PVC/02', pvc_supply(b), 6)}
lay = []
for ln in P[5].split('\n'):
    m = re.match(r'^\s*(\d{2,3})\s*(?:SCJ)?\s+((?:[\d,]+\.\d\d\s+){5}[\d,]+\.\d\d)\s*$', ln)
    if m: v = [num(x) for x in m.group(2).split()]; lay.append([int(m.group(1)), v[0], v[2], v[3], v[4], v[5]])
D['pvc']['laying'] = expect('A-PVC/03', lay, 6)
# Annex 02 – DI
di1, di2, di3 = rows(7, 10, 80), rows(8, 10, 80), rows(9, 8, 80)
D['di'] = {'supplyAsian': [[r[0], r[6], r[10]] for r in expect('A-DI/1', di1, 18)],
           'supplyNonAsian': [[r[0], r[6], r[10]] for r in expect('A-DI/2', di2, 18)],
           'laying': [[r[0], r[3], r[5], r[6], r[7], r[8]] for r in expect('A-DI/3', di3, 18)]}
# Annex 03 – HDPE (A-PE/01-06) and Annex 12 local (B-PE/01B, 03B)
sup = lambda pg: [[r[0], r[6], r[10]] for r in rows(pg, 10)]
layh = lambda pg: [[r[0], r[3], r[5], r[6], r[7], r[8]] for r in rows(pg, 8)]
def local(pg):
    r = []
    for ln in P[pg - 1].split('\n'):
        m = re.match(r'^\s*(\d{2,4})\s+([\d,]+\.\d\d)\s*$', ln)
        if m: r.append([int(m.group(1)), num(m.group(2))])
    return r
D['hdpe'] = {'pn10': {'supplyAsian': sup(10), 'supplyNonAsian': sup(11), 'laying': layh(14), 'local': local(103)},
             'pn16': {'supplyAsian': sup(12), 'supplyNonAsian': sup(13), 'laying': layh(15), 'local': local(106)}}
for k in ('pn10', 'pn16'):
    for t, v in D['hdpe'][k].items(): assert len(v) >= 10, (k, t, len(v))
# Annex 06 – chemicals
chem = []
for pg, tab in ((28, 'A-CH/01'), (29, 'A-CH/02')):
    for ln in P[pg - 1].split('\n'):
        m = re.match(r'^\s*(\d\.\d\d)\s+(.+?)\s{2,}(\S+)\s+(.*)$', ln)
        if not m or m.group(1) in ('1.00', '2.00'): continue
        vals = re.findall(r'[\d,]+\.\d\d|N/A', m.group(4))
        if not vals: continue
        rate = None if vals[-1] == 'N/A' else num(vals[-1])
        unit = m.group(3)
        kg = 1000 if unit == 't' else 900 if unit.startswith('900') else 68 if unit.startswith('68') else 1
        chem.append({'table': tab, 'item': m.group(1), 'name': m.group(2).strip(), 'unit': unit, 'rate': rate, 'derived_rate_LKR_per_kg': None if rate is None else round(rate / kg, 2)})
assert len(chem) == 13, len(chem)
D['chemicals'] = chem
# Annex 08 – basic prices (fuel); Annex 09 – labour
txt = '\f'.join(P)
fuel = {m.group(1).strip(): num(m.group(2)) for m in re.finditer(r'^\s*\d\s+((?:Petrol|Auto Diesel|Super Diesel|Kerosene|Industrial Kerosene)[^\n]*?)\s+l\s+([\d,]+\.\d\d)', txt, re.M)}
D['fuel'] = fuel
lab = []
for ln in P[85].split('\n'):
    m = re.match(r'^\s*(\d{1,2})\s+(.+?)\s+day\s+([\d,]+\.\d\d)\s*$', ln)
    if m: lab.append({'item': int(m.group(1)), 'trade': m.group(2).strip(), 'unit': 'day', 'rate': num(m.group(3))})
assert len(lab) == 17, len(lab)
D['labour'] = lab
# Annex 14 – exchange rates
m = re.search(r'1 USD = ([\d.]+) LKR', txt); e = re.search(r'1 EURO = ([\d.]+) LKR', txt)
D['fx'] = {'usd': float(m.group(1)), 'eur': float(e.group(1)), 'date': '2026-08-31', 'ref': 'Annex 14 – CBSL selling rate 31.08.2026'}
D['meta'] = {'circular': 'CQS/22/2026/98', 'date': '2026-10-14', 'title': 'NWSDB Rates 2026 (RB 2025 Rev. 01-2026)', 'labourSource': 'Market prices August 2026'}
open(out, 'w').write('// AUTO-GENERATED by scripts/ratebook/rb2026.py from the NWSDB Rates 2026 circular CQS/22/2026/98 (14.10.2026) – replaced tables only\n// eslint-disable-next-line\nexport const RB26 = ' + json.dumps(D) + ';\n')
print({k: (len(v) if isinstance(v, list) else list(v)[:6]) for k, v in D.items()})
print('fuel', fuel, 'fx', D['fx'])
